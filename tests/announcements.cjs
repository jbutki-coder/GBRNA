'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const section=html.split('<section id="announcements"')[1].split('</section>')[0];
for(const text of ['Grateful Wake Up Group','nafindlay.org','billwild.net','/fsc/','February 19-21, 2027','November 13, 2026','November 14, 2026','All Hallows Church','Volume 63','Volume 64','Autonomous Region FOR Narcotics Anonymous','first Sunday','Meeting link coming soon']) assert.ok(section.includes(text),text);
for(const [,src] of section.matchAll(/(?:src|href)="(\/images\/announcements\/[^"?]+)"/g)) assert.ok(fs.existsSync(path.join(root,src)),src);
assert.equal((html.match(/id="announcements"/g)||[]).length,1);
const grey=require('../data/literature-library.json').books.find(b=>b.id==='grey-book');
assert.equal(grey.pdf,'/literature/1981-NA-Basic-Text-Grey-Book-Manuscript.pdf');
assert.ok(html.includes(`href="${grey.pdf}"`));
assert.ok(!grey.readerUrl && !grey.downloadUrl);
assert.ok(fs.existsSync(path.join(root,grey.pdf)));
const {nextMeeting,format,zones}=require('../js/announcements.js');
const next=nextMeeting(new Date('2026-10-20T12:00:00Z'));
assert.equal(next.toISOString(),'2026-11-01T19:00:00.000Z');
assert.match(format(next,'America/Los_Angeles'),/11:00 AM/);
assert.match(format(next,'America/Chicago'),/1:00 PM/);
assert.match(format(next,'Asia/Kolkata'),/Nov 2, 12:30 AM/);
assert.match(format(next,'Pacific/Auckland'),/Nov 2, 8:00 AM/);
assert.equal(nextMeeting(new Date('2026-07-01T00:00:00Z')).toISOString(),'2026-07-05T18:00:00.000Z');
assert.equal(nextMeeting(new Date('2026-11-01T20:00:00Z')).toISOString(),'2026-12-06T19:00:00.000Z');
assert.equal(nextMeeting(new Date('2026-12-31T20:00:00Z')).toISOString(),'2027-01-03T19:00:00.000Z');
assert.equal(zones.length,20);
console.log('PASS: announcements, local Grey Book, assets, 20 time zones, DST, international date rollover, monthly and year rollover.');
