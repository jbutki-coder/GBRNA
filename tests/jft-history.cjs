'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const readings=require('../data/just-for-today.json');
const reading=readings.find(r=>r.id==='10-14');
assert.equal(readings.filter(r=>r.historyTitle).length,1);
const context={document:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,'js/just-for-today.js'),'utf8').split('init().catch')[0],context);
const note=context.renderHistoryNote(reading);
assert.ok(note.includes('Some NA History'));
assert.ok(note.includes('No Excuse for Loneliness'));
assert.ok(note.includes('Gina H.'));
assert.equal(reading.source, 'No page reference given');
assert.ok(note.includes('gives no page reference'));
assert.ok(note.includes('current JFT pairs with the Sixth Edition Basic Text, not the Fifth Edition'));
assert.ok(!note.includes('262'));
assert.ok(note.includes(reading.historyAudioUrl));
assert.equal(context.renderHistoryNote(readings.find(r=>r.id==='10-15')),'');
const {renderReader}=require('../translation-reader.cjs');
const translated=renderReader({book:'jft',reading:'10-14'},true);
assert.ok(translated.includes('Some NA History'));
assert.ok(translated.includes(reading.historyAudioUrl));
assert.ok(!renderReader({book:'jft',reading:'10-15'},true).includes('Some NA History'));
console.log('PASS: October 14 history note, remembrance link, date isolation, and translation rendering.');
